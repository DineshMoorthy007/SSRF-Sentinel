import os
import json
import unittest
from reporting.html_reporter import HTMLReporter


class TestHTMLReporter(unittest.TestCase):
    """
    Test suite for HTMLReporter covering all test conditions:
    A. Real JSON report generated by actual C++ target scan
    B. Report with multiple vulnerabilities
    C. Report with zero vulnerabilities (clean / secure mode)
    D. Report with inconclusive results
    E. Report containing missing optional fields
    F. HTML escaping and XSS safety

    All test outputs are isolated inside `tests/outputs/` to ensure
    the production `reports/` directory remains pristine.
    """

    @classmethod
    def setUpClass(cls):
        cls.base_dir = os.path.dirname(os.path.abspath(__file__))
        cls.fixtures_dir = os.path.join(cls.base_dir, "fixtures")
        cls.output_dir = os.path.join(cls.base_dir, "outputs")
        os.makedirs(cls.output_dir, exist_ok=True)
        os.makedirs(cls.fixtures_dir, exist_ok=True)
        # Configure HTMLReporter to write exclusively to tests/outputs/
        cls.reporter = HTMLReporter(report_dir=cls.output_dir)

    def _load_fixture(self, filename: str) -> dict:
        fixture_path = os.path.join(self.fixtures_dir, filename)
        with open(fixture_path, "r", encoding="utf-8") as f:
            return json.load(f)

    def test_a_real_json_report_rendering(self):
        """Scenario A: Render HTML from the actual C++ target JSON report or fixture."""
        real_json_path = os.path.join("reports", "ssrf_report.json")
        if not os.path.exists(real_json_path):
            real_json_path = os.path.join(self.fixtures_dir, "fixture_multi_vuln.json")

        html_path = self.reporter.generate_from_file(real_json_path, output_filename="test_real_report.html")
        self.assertTrue(os.path.exists(html_path))
        self.assertTrue(html_path.startswith(self.output_dir))

        with open(html_path, "r", encoding="utf-8") as f:
            html_content = f.read()

        with open(real_json_path, "r", encoding="utf-8") as f:
            json_data = json.load(f)

        # Verify header & metadata
        self.assertIn(json_data["project"], html_content)
        self.assertIn(json_data["target"], html_content)
        self.assertIn("SSRF Security Assessment Report", html_content)

        # Verify summary counts match JSON exactly
        summary = json_data["summary"]
        self.assertIn(f"Endpoints Discovered</div>\n          <div class=\"stat-number\">{summary['endpoints_discovered']}</div>", html_content)
        self.assertIn(f"Unique Findings</div>\n          <div class=\"stat-number\">{summary['unique_findings']}</div>", html_content)

        # Verify all vulnerability IDs appear
        for vuln in json_data.get("vulnerabilities", []):
            self.assertIn(vuln["id"], html_content)
            self.assertIn(vuln["name"], html_content)
            self.assertIn(vuln["endpoint"], html_content)
            self.assertIn(vuln["parameter"], html_content)

    def test_b_multiple_vulnerabilities(self):
        """Scenario B: Report containing multiple distinct vulnerabilities."""
        synthetic_data = self._load_fixture("fixture_multi_vuln.json")

        html_path = self.reporter.generate_report(synthetic_data, output_filename="test_multi_vuln.html")
        self.assertTrue(os.path.exists(html_path))
        self.assertTrue(html_path.startswith(self.output_dir))

        with open(html_path, "r", encoding="utf-8") as f:
            content = f.read()

        self.assertIn("SSRF-001", content)
        self.assertIn("SSRF-002", content)
        self.assertIn("SSRF-003", content)
        self.assertIn("CRITICAL RISK", content)
        self.assertIn("Critical (1)", content)
        self.assertIn("High (1)", content)
        self.assertIn("Medium (1)", content)

    def test_c_zero_vulnerabilities(self):
        """Scenario C: Clean target or hardened secure mode report with zero vulnerabilities."""
        clean_data = self._load_fixture("fixture_clean_report.json")

        html_path = self.reporter.generate_report(clean_data, output_filename="test_zero_vuln.html")
        self.assertTrue(os.path.exists(html_path))
        self.assertTrue(html_path.startswith(self.output_dir))

        with open(html_path, "r", encoding="utf-8") as f:
            content = f.read()

        # Verify safe banner and clean state box
        self.assertIn("SECURE POSTURE", content)
        self.assertIn("Zero Vulnerabilities Identified", content)
        self.assertIn("All tested parameters successfully rejected unauthorized server-side requests", content)
        self.assertNotIn("vuln-card expanded", content)

    def test_d_inconclusive_results(self):
        """Scenario D: Report containing inconclusive test outcomes."""
        inconclusive_data = self._load_fixture("fixture_inconclusive.json")

        html_path = self.reporter.generate_report(inconclusive_data, output_filename="test_inconclusive.html")
        self.assertTrue(html_path.startswith(self.output_dir))

        with open(html_path, "r", encoding="utf-8") as f:
            content = f.read()

        self.assertIn("Inconclusive Tests</div>\n          <div class=\"stat-number\">5</div>", content)

    def test_e_missing_optional_fields(self):
        """Scenario E: Report with missing optional fields rendered without crashing."""
        sparse_data = self._load_fixture("fixture_sparse.json")

        # Must not raise an exception
        html_path = self.reporter.generate_report(sparse_data, output_filename="test_sparse.html")
        self.assertTrue(os.path.exists(html_path))
        self.assertTrue(html_path.startswith(self.output_dir))

        with open(html_path, "r", encoding="utf-8") as f:
            content = f.read()

        self.assertIn("Generic SSRF Finding", content)
        self.assertIn("SSRF-UNKNOWN", content)

    def test_f_html_escaping_and_xss_protection(self):
        """Scenario F: Dynamic content is safely escaped to prevent HTML injection."""
        malicious_data = self._load_fixture("fixture_xss.json")

        html_path = self.reporter.generate_report(malicious_data, output_filename="test_xss_escaped.html")
        self.assertTrue(html_path.startswith(self.output_dir))

        with open(html_path, "r", encoding="utf-8") as f:
            content = f.read()

        # Raw tags must NOT appear unescaped
        self.assertNotIn("<script>alert('xss-project')</script>", content)
        self.assertNotIn("<script>alert('xss-name')</script>", content)
        self.assertNotIn("<style>body{display:none}</style>", content)
        self.assertNotIn("<script>document.cookie</script>", content)

        # Escaped representations must be present
        self.assertIn("&lt;script&gt;alert(&#x27;xss-project&#x27;)&lt;/script&gt;", content)
        self.assertIn("&lt;script&gt;alert(&#x27;xss-name&#x27;)&lt;/script&gt;", content)
        self.assertIn("&lt;script&gt;document.cookie&lt;/script&gt;", content)


if __name__ == "__main__":
    unittest.main()
